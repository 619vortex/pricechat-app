/// Unknown fields are ignored (a later manifest may add some); a higher `schema` is refused.
#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
pub struct Manifest {
    pub schema: u32,
    pub product: String,
    pub channel: String,
    pub seq: u64,
    pub signed_at: String,
    pub expires_at: String,
    pub release: Release,
    #[serde(default)]
    pub pin_add: Vec<Pin>,
    #[serde(default)]
    pub revoke_keys: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
pub struct Release {
    pub version: String,
    #[serde(default)]
    pub min_version: Option<String>,
    #[serde(default)]
    pub security: bool,
    pub url: String,
    pub size: u64,
    pub sha256: String,
    #[serde(default)]
    pub notes: String,
    pub rollout_bp: u32,
    #[serde(default)]
    pub paused: bool,
}

/// What this PC knows when it judges a manifest. `highest`, `seq` and `revoked` come from the protected state.
#[derive(Debug, Clone)]
pub struct Context<'a> {
    pub now: u64,
    pub running: Version,
    pub highest: Option<Version>,
    pub seq: u64,
    pub product: &'a str,
    pub channel: &'a str,
    pub host: &'a str,
    pub install_id: &'a [u8],
}

#[derive(Debug, Clone, PartialEq)]
pub enum Offer {
    /// A valid manifest with nothing to install here, and why (shown in the log only).
    Nothing(&'static str),
    /// `required`: this install is below the release's `min_version`.
    Available { version: Version, required: bool, release: Release },
}

/// A full check: signature, then every field rule. On success also returns the key revocations this manifest may make (only keys
/// before its signer) and the pins it adds, both to be stored.
#[derive(Debug, Clone, PartialEq)]
pub struct Accepted {
    pub manifest: Manifest,
    pub offer: Offer,
    pub revoke: Vec<String>,
}

pub fn accept(bytes: &[u8], keys: &[Key], revoked: &[String], cx: &Context) -> Result<Accepted, Refused> {
    let (signer, payload) = open_envelope(bytes, UPDATE_PREFIX, keys, revoked)?;
    let manifest: Manifest = serde_json::from_slice(&payload).map_err(|_| Refused::Payload)?;
    let offer = check_manifest(&manifest, cx)?;
    let revoke = manifest.revoke_keys.iter().filter(|id| keys.iter().position(|k| &k.id == id).is_some_and(|i| i < signer)).cloned().collect();
    Ok(Accepted { manifest, offer, revoke })
}

pub fn sha256_hex_ok(s: &str) -> bool {
    s.len() == 64 && s.bytes().all(|c| c.is_ascii_hexdigit())
}

/// `https://<host>/downloads/kiwi/windows/<name>.exe`: no port, no userinfo, no query or fragment, plain path characters.
pub fn url_ok(url: &str, host: &str) -> bool {
    let Some(rest) = url.strip_prefix("https://") else { return false };
    let Some(path) = rest.strip_prefix(host) else { return false };
    path.starts_with(MANIFEST_DIR)
        && path.len() <= 200
        && path.ends_with(".exe")
        && path.bytes().all(|c| c.is_ascii_alphanumeric() || b"._-/".contains(&c))
        && !path.contains("..")
        && !path.contains("//")
        && path[MANIFEST_DIR.len()..].bytes().all(|c| c != b'/')
}

/// The path part of a URL `url_ok` accepted.
pub fn url_path<'a>(url: &'a str, host: &str) -> &'a str {
    url.strip_prefix("https://").and_then(|r| r.strip_prefix(host)).unwrap_or("/")
}

/// Which slice of installs gets a staged release: first 4 bytes of SHA-256(install id || version), mod 10,000.
pub fn bucket(install_id: &[u8], version: &str) -> u32 {
    let mut h = Sha256::new();
    h.update(install_id);
    h.update(version.as_bytes());
    let d = h.finalize();
    u32::from_be_bytes([d[0], d[1], d[2], d[3]]) % FULL_ROLLOUT
}

pub fn check_manifest(m: &Manifest, cx: &Context) -> Result<Offer, Refused> {
    if m.schema == 0 || m.schema > SCHEMA {
        return Err(Refused::Schema);
    }
    if m.product != cx.product {
        return Err(Refused::Product);
    }
    if m.channel != cx.channel {
        return Err(Refused::Channel);
    }
    if m.seq < cx.seq {
        return Err(Refused::OldSeq);
    }
    let signed = parse_time(&m.signed_at).ok_or(Refused::Payload)?;
    let expires = parse_time(&m.expires_at).ok_or(Refused::Payload)?;
    if expires <= cx.now {
        return Err(Refused::Expired);
    }
    if signed > cx.now + FUTURE_SLACK {
        return Err(Refused::FromTheFuture);
    }
    if expires <= signed || expires - signed > MAX_LIFETIME {
        return Err(Refused::TooLong);
    }
    let r = &m.release;
    let version = Version::parse(&r.version).ok_or(Refused::Version)?;
    let min = match &r.min_version {
        Some(v) => Some(Version::parse(v).ok_or(Refused::Version)?),
        None => None,
    };
    if min.is_some_and(|min| min > version) {
        return Err(Refused::Version);
    }
    if !url_ok(&r.url, cx.host) {
        return Err(Refused::Url);
    }
    if !(MIN_SIZE..=MAX_SIZE).contains(&r.size) {
        return Err(Refused::Size);
    }
    if !sha256_hex_ok(&r.sha256) {
        return Err(Refused::Hash);
    }
    if r.notes.chars().count() > MAX_NOTES {
        return Err(Refused::Notes);
    }
    if r.rollout_bp > FULL_ROLLOUT {
        return Err(Refused::Rollout);
    }
    for p in &m.pin_add {
        if p.sha1.len() != 40 || !p.sha1.bytes().all(|c| c.is_ascii_hexdigit()) || p.sha256.as_ref().is_some_and(|s| !sha256_hex_ok(s)) {
            return Err(Refused::Payload);
        }
    }
    if version <= cx.running || cx.highest.is_some_and(|h| version <= h) {
        return Ok(Offer::Nothing("not newer than this install"));
    }
    if r.paused {
        return Ok(Offer::Nothing("release paused"));
    }
    let required = min.is_some_and(|min| cx.running < min);
    if !required && !r.security && bucket(cx.install_id, &r.version) >= r.rollout_bp {
        return Ok(Offer::Nothing("not in this rollout stage yet"));
    }
    Ok(Offer::Available { version, required, release: r.clone() })
}

// ----- the download -----

/// Checks a download as it streams: never more than the manifest's size (cut off at the first extra byte), and on finishing,
/// exactly that size and that SHA-256.
pub struct Download {
    size: u64,
    sha256: [u8; 32],
    got: u64,
    hasher: Sha256,
}

impl Download {
    pub fn new(size: u64, sha256_hex: &str) -> Result<Download, Refused> {
        if !(MIN_SIZE..=MAX_SIZE).contains(&size) {
            return Err(Refused::Size);
        }
        Ok(Download { size, sha256: parse_sha256(sha256_hex).ok_or(Refused::Hash)?, got: 0, hasher: Sha256::new() })
    }
    pub fn feed(&mut self, chunk: &[u8]) -> Result<(), Refused> {
        if self.got + chunk.len() as u64 > self.size {
            return Err(Refused::Oversize);
        }
        self.got += chunk.len() as u64;
        self.hasher.update(chunk);
        Ok(())
    }
    pub fn finish(self) -> Result<(), Refused> {
        if self.got < self.size {
            return Err(Refused::Truncated);
        }
        let got: [u8; 32] = self.hasher.finalize().into();
        if got != self.sha256 {
            return Err(Refused::HashMismatch);
        }
        Ok(())
    }
}

pub fn parse_sha256(hex: &str) -> Option<[u8; 32]> {
    if !sha256_hex_ok(hex) {
        return None;
    }
    let mut out = [0u8; 32];
    for (i, o) in out.iter_mut().enumerate() {
        *o = u8::from_str_radix(&hex[2 * i..2 * i + 2], 16).ok()?;
    }
    Some(out)
}

pub fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes).iter().map(|b| format!("{b:02X}")).collect()
}

// ----- the installer's Authenticode signature -----

/// What Windows said about the installer's signature, read from the verified copy by handle.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Signer {
    /// WinVerifyTrust accepted the whole chain, with revocation checked.
    pub trusted: bool,
    pub sha1: String,
    pub sha256: String,
    /// The signature carries a timestamp countersignature, so it stays valid after the certificate expires.
    pub timestamped: bool,
}

pub fn pinned(signer: &Signer, pins: &[Pin]) -> bool {
    signer.sha1.len() == 40
        && pins.iter().any(|p| p.sha1.eq_ignore_ascii_case(&signer.sha1) && p.sha256.as_ref().is_none_or(|s| s.eq_ignore_ascii_case(&signer.sha256)))
}

/// The last word before an installer runs. `signer` None: no signature at all.
pub fn installer_ok(signer: Option<&Signer>, pins: &[Pin], file_version: Option<Version>, want: Version) -> Result<(), Refused> {
    let s = signer.ok_or(Refused::NotSigned)?;
    if !s.trusted {
        return Err(Refused::NotSigned);
    }
    if !pinned(s, pins) {
        return Err(Refused::NotPinned);
    }
    if !s.timestamped {
        return Err(Refused::NoTimestamp);
    }
    if file_version != Some(want) {
        return Err(Refused::VersionResource);
    }
    Ok(())
}

/// The version a repair or recovery may run: never below the committed one.
pub fn may_run(version: Version, highest: Option<Version>, repair: bool) -> Result<(), Refused> {
    match highest {
        Some(h) if version < h => Err(Refused::Downgrade),
        Some(h) if version == h && !repair => Err(Refused::Downgrade),
        _ => Ok(()),
    }
}

