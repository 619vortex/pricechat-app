//! Signed auto-update (docs/AUTO-UPDATE.md), as plain rules with tests. `update_win` does the Windows half: the download, the
//! Authenticode check, the protected state and starting the installer. Nothing here touches the network or the disk.
//!
//! Two signatures, and an installer runs only if both hold:
//! - an Ed25519 signature (RFC 8032, `verify_strict`) over `"kiwi-update-v1\n" || payload`, by a key compiled into the service;
//! - the installer's Authenticode signature, chained and timestamped, by a certificate whose thumbprint is pinned here.
//!
//! The signed server list (audit I2) uses the same keys under a different prefix, `"kiwi-servers-v1\n"`, so a signature made for
//! one can never be taken for the other.

use base64::{engine::general_purpose::STANDARD, Engine};
use ed25519_dalek::{Signature, VerifyingKey};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

pub const UPDATE_PREFIX: &[u8] = b"kiwi-update-v1\n";
pub const SERVERS_PREFIX: &[u8] = b"kiwi-servers-v1\n";
pub const PRODUCT: &str = "kiwivpn-windows";
pub const SCHEMA: u32 = 1;
pub const MAX_MANIFEST: usize = 64 * 1024;
pub const MIN_SIZE: u64 = 1024 * 1024;
pub const MAX_SIZE: u64 = 100 * 1024 * 1024;
pub const MAX_NOTES: usize = 2000;
/// A manifest may be valid for at most this long after it was signed (we sign for 14 days).
pub const MAX_LIFETIME: u64 = 30 * 86_400;
/// How far in the future `signed_at` may be on this PC's clock.
pub const FUTURE_SLACK: u64 = 86_400;
pub const FULL_ROLLOUT: u32 = 10_000;

/// One manifest key. Order matters: a key may only revoke keys before it (k2 revokes k1, never the reverse).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Key {
    pub id: &'static str,
    pub public: [u8; 32],
}

const fn nibble(c: u8) -> u8 {
    match c {
        b'0'..=b'9' => c - b'0',
        b'a'..=b'f' => c - b'a' + 10,
        _ => panic!("not lower-case hex"),
    }
}

const fn hex32(s: &str) -> [u8; 32] {
    let b = s.as_bytes();
    assert!(b.len() == 64, "a key is 64 hex characters");
    let mut out = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        out[i] = (nibble(b[2 * i]) << 4) | nibble(b[2 * i + 1]);
        i += 1;
    }
    out
}

