// ----- versions -----

/// `major.minor.patch`, numbers only: no pre-release tags, no leading zeros, nothing else.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Version(pub u32, pub u32, pub u32);

impl Version {
    pub fn parse(text: &str) -> Option<Version> {
        let parts: Vec<&str> = text.split('.').collect();
        if parts.len() != 3 {
            return None;
        }
        let mut n = [0u32; 3];
        for (i, p) in parts.iter().enumerate() {
            if p.is_empty() || p.len() > 5 || !p.bytes().all(|c| c.is_ascii_digit()) || (p.len() > 1 && p.starts_with('0')) {
                return None;
            }
            n[i] = p.parse().ok()?;
        }
        Some(Version(n[0], n[1], n[2]))
    }
}

impl std::fmt::Display for Version {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}.{}.{}", self.0, self.1, self.2)
    }
}

/// This build's own version. The CI update test builds its "previous version" from the same source and says so here.
pub fn running_version() -> Version {
    #[cfg(feature = "update-test")]
    {
        if let Some(v) = option_env!("KIWI_UPDATE_TEST_VERSION").and_then(Version::parse) {
            return v;
        }
    }
    Version::parse(env!("CARGO_PKG_VERSION")).unwrap_or(Version(0, 0, 0))
}

// ----- time -----

/// Unix seconds from exactly `YYYY-MM-DDTHH:MM:SSZ`.
pub fn parse_time(text: &str) -> Option<u64> {
    let b = text.as_bytes();
    if b.len() != 20 || b[4] != b'-' || b[7] != b'-' || b[10] != b'T' || b[13] != b':' || b[16] != b':' || b[19] != b'Z' {
        return None;
    }
    let num = |from: usize, to: usize| -> Option<i64> {
        let s = &text[from..to];
        if s.bytes().all(|c| c.is_ascii_digit()) {
            s.parse().ok()
        } else {
            None
        }
    };
    let (y, mo, d, h, mi, s) = (num(0, 4)?, num(5, 7)?, num(8, 10)?, num(11, 13)?, num(14, 16)?, num(17, 19)?);
    if !(1970..=9999).contains(&y) || !(1..=12).contains(&mo) || !(1..=31).contains(&d) || h > 23 || mi > 59 || s > 59 {
        return None;
    }
    // days from the civil date (Howard Hinnant's algorithm)
    let yy = if mo <= 2 { y - 1 } else { y };
    let era = yy.div_euclid(400);
    let yoe = yy - era * 400;
    let mp = (mo + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    let days = era * 146_097 + doe - 719_468;
    u64::try_from(days * 86_400 + h * 3600 + mi * 60 + s).ok()
}

// ----- the envelope -----

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Envelope {
    key_id: String,
    payload: String,
    sig: String,
}

/// Checks the signature before anything in the payload is read. Returns the signer's position in `keys` and the payload bytes.
pub fn open_envelope(bytes: &[u8], prefix: &[u8], keys: &[Key], revoked: &[String]) -> Result<(usize, Vec<u8>), Refused> {
    if bytes.len() > MAX_MANIFEST {
        return Err(Refused::TooLarge);
    }
    let env: Envelope = serde_json::from_slice(bytes).map_err(|_| Refused::Envelope)?;
    let index = keys.iter().position(|k| k.id == env.key_id).ok_or(Refused::UnknownKey)?;
    if revoked.iter().any(|r| r == &env.key_id) {
        return Err(Refused::RevokedKey);
    }
    let key = keys[index];
    if key.public == [0; 32] {
        return Err(Refused::KeyNotSet);
    }
    let payload = STANDARD.decode(env.payload.as_bytes()).map_err(|_| Refused::Envelope)?;
    let sig: [u8; 64] = STANDARD.decode(env.sig.as_bytes()).map_err(|_| Refused::Envelope)?.try_into().map_err(|_| Refused::BadSignature)?;
    let vk = VerifyingKey::from_bytes(&key.public).map_err(|_| Refused::KeyNotSet)?;
    let mut message = Vec::with_capacity(prefix.len() + payload.len());
    message.extend_from_slice(prefix);
    message.extend_from_slice(&payload);
    vk.verify_strict(&message, &Signature::from_bytes(&sig)).map_err(|_| Refused::BadSignature)?;
    Ok((index, payload))
}

