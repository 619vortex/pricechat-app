/// An install in flight, kept in the protected state.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Pending {
    pub version: String,
    pub sha256: String,
    pub started_at: u64,
    #[serde(default)]
    pub attempts: u32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Health {
    /// No update in flight.
    Idle,
    /// The new version is the one running: commit it.
    Commit,
    /// Something else is running: the recovery path (re-run the new installer once, then the repair copy).
    Recover,
}

pub fn after_start(pending: Option<&Pending>, running: Version) -> Health {
    match pending {
        None => Health::Idle,
        Some(p) if Version::parse(&p.version) == Some(running) => Health::Commit,
        Some(_) => Health::Recover,
    }
}

