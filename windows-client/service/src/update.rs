/// One server the app may connect to. The service compares a connect's endpoint and server key against this list.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ListedServer {
    pub id: i64,
    /// `ip:port` or `host:port`, as in the config's Endpoint.
    pub endpoint: String,
    /// The server's WireGuard public key, base64.
    pub public_key: String,
}

#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]
pub struct ServerList {
    pub schema: u32,
    pub product: String,
    pub seq: u64,
    pub signed_at: String,
    pub expires_at: String,
    pub servers: Vec<ListedServer>,
}

pub const SERVER_LIST_PRODUCT: &str = "kiwivpn-servers";

/// A server list signed with the same keys under SERVERS_PREFIX: an update manifest's signature never verifies here.
pub fn accept_server_list(bytes: &[u8], keys: &[Key], revoked: &[String], now: u64, seq: u64) -> Result<ServerList, Refused> {
    let (_, payload) = open_envelope(bytes, SERVERS_PREFIX, keys, revoked)?;
    let list: ServerList = serde_json::from_slice(&payload).map_err(|_| Refused::Payload)?;
    if list.schema == 0 || list.schema > SCHEMA {
        return Err(Refused::Schema);
    }
    if list.product != SERVER_LIST_PRODUCT {
        return Err(Refused::Product);
    }
    if list.seq < seq {
        return Err(Refused::OldSeq);
    }
    let signed = parse_time(&list.signed_at).ok_or(Refused::Payload)?;
    let expires = parse_time(&list.expires_at).ok_or(Refused::Payload)?;
    if expires <= now {
        return Err(Refused::Expired);
    }
    if signed > now + FUTURE_SLACK {
        return Err(Refused::FromTheFuture);
    }
    if expires <= signed || expires - signed > MAX_LIFETIME {
        return Err(Refused::TooLong);
    }
    Ok(list)
}

/// Whether a config's server is on the signed list: the same endpoint and the same server key.
pub fn server_listed(list: &ServerList, endpoint: &str, public_key: &str) -> bool {
    list.servers.iter().any(|s| s.endpoint.eq_ignore_ascii_case(endpoint) && s.public_key == public_key)
}

